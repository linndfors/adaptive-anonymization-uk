def category(label: str, l1: str) -> tuple[str, str] | None:
    """Return (level-1 name, level-2 name) for a closed id; None for unknown ids or 'none'."""
    spec = TAXONOMY.get(label)
    if not spec or l1 not in spec["categories"]:
        return None
    name, domain, _hint = spec["categories"][l1]
    return name, spec["domains"][domain]


def map_key(label: str, value: str) -> str:
    return f"{label}::{norm(value)}"


def is_trivial(value: str, parent: str) -> bool:
    """A parent is no generalization when it equals or literally contains the value."""
    v, p = norm(value), norm(parent)
    return not v or v == p or re.search(rf"(?<!\w){re.escape(v)}(?!\w)", p) is not None


@lru_cache(maxsize=4)
def _load(path: str) -> dict:
    file = Path(path)
    if not file.exists():
        return {}
    return json.loads(file.read_text(encoding="utf-8")).get("entries", {})


def lookup(label: str, value: str, path: str | Path | None = None) -> list[tuple[str, str, float]]:
    """Cached closed-vocabulary parents in the shape of ``action_space._parents``."""
    entry = _load(str(path or MAP_PATH)).get(map_key(label, value))
    names = category(label, entry.get("l1") or NONE) if entry else None
    if names is None or any(is_trivial(value, name) for name in names):
        return []
    return [(names[0], TOOL, 0.2), (names[1], TOOL, 0.4)]
